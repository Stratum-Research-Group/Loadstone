"""Dataset registry: suite identities, versions and canonical examples.

Only the MQAR suite is implemented at Milestone 1. S5 / Rule110 / addition /
enwik8 are registered as *not implemented* so planning can never silently
substitute a different task.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol

MQAR_SUITE = "mqar_controlled_v1"
MQAR_VERSION = "1.0.0"


@dataclass(frozen=True)
class SuiteInfo:
    suite: str
    version: str
    implemented: bool
    licence_note: str
    description: str


REGISTRY: dict[str, SuiteInfo] = {
    MQAR_SUITE: SuiteInfo(
        suite=MQAR_SUITE,
        version=MQAR_VERSION,
        implemented=True,
        licence_note="Synthetic, generated by this repository. No third-party data.",
        description="Controlled multi-query associative recall (spec section 7).",
    ),
    "s5_permutation_v1": SuiteInfo(
        "s5_permutation_v1", "0.0.0", False, "Synthetic, not yet generated.", "Suite B1 (spec 8)."
    ),
    "rule110_v1": SuiteInfo(
        "rule110_v1", "0.0.0", False, "Synthetic, not yet generated.", "Suite B2 (spec 8)."
    ),
    "decimal_addition_v1": SuiteInfo(
        "decimal_addition_v1", "0.0.0", False, "Synthetic, not yet generated.", "Suite B3 (spec 8)."
    ),
    "enwik8_bytes_v1": SuiteInfo(
        "enwik8_bytes_v1",
        "0.0.0",
        False,
        "enwik8 is redistributed by its maintainer; not bundled here. Verify terms before download.",
        "Suite C (spec 9).",
    ),
}


class ExampleSource(Protocol):
    def examples(self, split: str, cell_id: str) -> list: ...

    def cells(self) -> list[str]: ...


def suite_info(name: str) -> SuiteInfo:
    if name not in REGISTRY:
        raise KeyError(f"unknown suite {name!r}; known: {sorted(REGISTRY)}")
    return REGISTRY[name]


def require_implemented(name: str) -> SuiteInfo:
    info = suite_info(name)
    if not info.implemented:
        raise NotImplementedError(
            f"suite {name!r} is registered but not implemented at this milestone; "
            "it must not be substituted by another task"
        )
    return info
